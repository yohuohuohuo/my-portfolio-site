export const getRandomBird = (width: number, height: number, plus?: boolean) => {
  const x = -width / 2 - (plus ? random(800, width / 2) : random(200, 1000));
  const y = random(200, height / 2) * (Math.random() > 0.5 ? -1 : 1);
  return { x, y, d: clamp(random(-2, 2), -1, 1) };
};

export const covetPoint = (x: number, y: number, w: number, h: number, scale: number) => {
  return { x: (w / 2 - x) / scale, y: (h / 2 - y) / scale };
};
